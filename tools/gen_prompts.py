def write(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8")


def card(rows: list[tuple[str, str]]) -> str:
    return "\n".join(["| | |", "|---|---|"] + [f"| **{k}** | {v} |" for k, v in rows])


def prompt_file(title, meta, attach, prompt, negative, notes, checks) -> str:
    """프롬프트는 부정까지 포함해 한 덩어리다.

    부정을 별도 블록으로 떼어놓으면 복사할 때 빠뜨린다. 실제로 빠뜨렸고,
    막으려던 "주황빛 일출"이 그대로 나왔다. 그래서 마지막 문장으로 붙인다.
    """
    p = [f"# {title}", "", card(meta), "", notes, "",
         "## 넣는 법", "", attach, "",
         "## 프롬프트 — 아래 상자를 통째로 복사하세요", "",
         "```text", prompt, "",
         "마지막으로, 다음은 절대 넣지 마세요 — " + negative.strip().rstrip(",.") + ".",
         "```", "",
         "## 받고 나서 확인할 것", ""]
    p += [f"- [ ] {c}" for c in checks]
    return "\n".join(p)


